export function translate(
  locale: Locale,
  key: MessageKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) =>
      message.replaceAll(
        `{${name}}`,
        typeof value === "number" ? formatNumber(locale, value) : value,
      ),
    messages[locale][key],
  );
}
